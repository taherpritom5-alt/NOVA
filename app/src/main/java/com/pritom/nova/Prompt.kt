        val role = roleText.getOrElse(s.role) { roleText[0] }
        val now = SimpleDateFormat("EEEE, d MMMM yyyy, h:mm a", Locale.US).format(Date())
        val facts = s.facts.ifBlank { "(এখনো কিছু নেই)" }
        val msgs = s.recentMessagesText().ifBlank { "(কোনো মেসেজ নেই, অথবা Notification access এখনো চালু হয়নি)" }
